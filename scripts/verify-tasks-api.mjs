import assert from 'node:assert/strict';
import {randomBytes} from 'node:crypto';
const base=process.argv[2];
assert.match(base||'',/^http:\/\/127\.0\.0\.1:\d{4,5}$/);
let checks=0;
async function request(method,path,body,token,status=200){
 const response=await fetch(base+'/api'+path,{method,headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},body:body===undefined?undefined:JSON.stringify(body)});
 const value=response.status===204?null:await response.json();
 assert.equal(response.status,status,method+' '+path+': '+JSON.stringify(value));checks++;return value;
}
const suffix=randomBytes(4).toString('hex'),password=randomBytes(18).toString('hex');
async function account(prefix){
 const username=prefix+suffix;
 await request('POST','/auth/register',{username,displayName:prefix,password},null,201);
 return request('POST','/auth/login',{username,password});
}
const [owner,a,b,out]=await Promise.all(['leader','memberA','memberB','outsider'].map(account));
const p=await request('POST','/projects',{name:'0.3 '+suffix},owner.token,201);
const prefix='/projects/'+p.id;
const inv=await request('POST',prefix+'/invitations',{validHours:1},owner.token,201);
for(const u of [a,b])await request('POST','/invitations/join',{code:inv.code},u.token);
const create=(title,assigneeId)=>request('POST',prefix+'/tasks',{title,description:'成果说明',assigneeId,dueAt:'2020-01-01T00:00:00Z'},owner.token,201);
const act=(t,action,u,extra={},status=200)=>request('POST',prefix+'/tasks/'+t.id+'/'+action,{version:t.version,...extra},u.token,status);
const acts=()=>request('GET',prefix+'/activities',undefined,owner.token);
await request('GET',prefix+'/tasks',undefined,out.token,404);
await request('POST',prefix+'/tasks',{title:'越权'},a.token,403);
const t=await create('并发领取');
assert.equal(t.status,'OPEN');assert.equal(t.overdue,true);
const raced=await Promise.all([a,b].map(async user=>{
 const res=await fetch(base+'/api'+prefix+'/tasks/'+t.id+'/claim',{method:'POST',headers:{'Content-Type':'application/json',Authorization:'Bearer '+user.token},body:JSON.stringify({version:0})});
 return {status:res.status,value:await res.json(),user};
}));
assert.deepEqual(raced.map(x=>x.status).sort(),[200,409]);checks+=2;
let current=raced.find(x=>x.status===200).value;
const responsible=raced.find(x=>x.status===200).user;
const reviewer=responsible.user.id===a.user.id?b:a;
assert.equal((await acts()).filter(e=>e.kind==='CLAIM').length,1);
await act(t,'claim',out,{},404);
await act(current,'start',reviewer,{},403);
current=await act(current,'start',responsible);
const stale=current;
current=await act(current,'submit',responsible,{text:'第一轮成果'});
assert.equal(current.status,'IN_REVIEW');
await act(stale,'submit',responsible,{text:'重复'},409);
const before=(await acts()).length;
await act(current,'return',owner,{text:' '},400);
assert.equal((await acts()).length,before);
await act(current,'accept',reviewer,{},403);
current=await act(current,'delegate',owner,{memberId:reviewer.user.id});
current=await act(current,'review',reviewer,{text:'需要完善边界'});
assert.equal(current.status,'IN_REVIEW');
await act(current,'accept',reviewer,{},403);
await act(current,'review',reviewer,{text:'覆盖'},400);
current=await act(current,'return',owner,{text:'补齐校验'});
assert.equal(current.assigneeId,responsible.user.id);
current=await act(current,'submit',responsible,{text:'第二轮成果'});
current=await act(current,'accept',owner);
assert.equal(current.status,'DONE');assert.equal(current.overdue,false);
const history=await request('GET',prefix+'/tasks/'+t.id+'/rounds',undefined,owner.token);
assert.equal(history.length,2);
assert.equal(history[0].decision,'ACCEPTED');
assert.equal(history[1].decision,'RETURNED');
assert.equal(history[1].opinion,'需要完善边界');
await act(current,'return',owner,{text:'不能重开'},409);
const other=await request('POST','/projects',{name:'其他项目'},owner.token,201);
await request('GET','/projects/'+other.id+'/tasks/'+t.id+'/rounds',undefined,owner.token,404);
await request('POST','/projects/'+other.id+'/tasks/'+t.id+'/cancel',{version:current.version,text:'跨项目'},owner.token,404);
let assigned=await create('调整任务',a.user.id);
await request('POST',prefix+'/members/'+a.user.id+'/remove',{reason:'未完成'},owner.token,400);
assigned=await act(assigned,'assign',owner,{memberId:b.user.id,text:'交接'});
assert.equal(assigned.assigneeId,b.user.id);
assigned=await act(assigned,'deadline',owner,{dueAt:null,text:'取消截止'});
assert.equal(assigned.dueAt,null);
assigned=await act(assigned,'cancel',owner,{text:'不再需要'});
assert.equal(assigned.status,'CANCELED');
await request('POST',prefix+'/members/'+a.user.id+'/remove',{reason:'离开项目'},b.token,403);
await request('POST',prefix+'/members/'+a.user.id+'/remove',{reason:'离开项目'},owner.token,204);
await request('GET',prefix+'/tasks',undefined,a.token,404);
await request('GET',prefix+'/activities',undefined,a.token,404);
await request('POST',prefix+'/members/'+owner.user.id+'/remove',{reason:'自己'},owner.token,400);
console.log('0.3 integration PASS: '+checks+' HTTP checks; atomic claim, permissions, version conflicts, history and member removal.');

